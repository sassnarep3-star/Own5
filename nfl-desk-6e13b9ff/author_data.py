def w(name, header, rows):
    path = os.path.join(OUT, name)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        wr = csv.writer(fh, lineterminator="\n")
        wr.writerow(header)
        wr.writerows(rows)
    print(f"wrote {name}: {len(rows)} rows")


def ev(*paths):
    """Join evidence parts; assert every in-repo path exists (no hallucinated links)."""
    parts = []
    for p in paths:
        if p.startswith("http"):
            if not p.startswith(ALLOWED_EVIDENCE_HOSTS):
                raise SystemExit(f"evidence URL host not allowed: {p}")
            parts.append(p)
        else:
            # Desk pages are generated by build_desk.py after this run; verify_desk.py
            # re-checks every evidence path (including generated pages) after the build.
            if not p.startswith(("nfl-desk-6e13b9ff/", "data/nfl-desk-6e13b9ff/")):
                full = os.path.join(REPO, p)
                if not os.path.exists(full):
                    raise SystemExit(f"evidence path does not exist: {p}")
            parts.append(p)
    return " ;; ".join(parts)


