def badge(s):
    cls = s.replace(' ', '').replace('-', '')
    cls = 'NOTSTARTED' if cls == 'NOTSTARTED' else cls
    return f'<span class="badge {E(cls)}">{E(s)}</span>'

def link(url, label="official source"):
    if not url: return '<span class="badge UNV">UNVERIFIED</span>'
    if not url.startswith('http'): return '<span class="badge">internal evidence only</span>'
    return f'<a href="{E(url)}" rel="noopener">{E(label)}</a>'

def table(headers, rows, cls=""):
    th = "".join(f"<th>{E(h)}</th>" for h in headers)
    trs = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tw"><table class="{cls}"><thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table></div>'

def cards(items):
    return '<div class="cards">' + "".join(f'<div class="card"><b>{E(v)}</b><span>{E(k)}</span></div>' for k, v in items) + '</div>'

