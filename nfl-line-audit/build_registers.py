REPO_BLOB = "https://github.com/sassnarep3-star/Own5/blob/main/nfl-line-audit/data/"


def stamp_source(rows, fallback="preregistration.json"):
    """Every published register row must carry a link a reviewer can open."""
    for r in rows:
        if r.get("source_url"):
            continue
        ev = r.get("evidence_url") or r.get("evidence_path") or ""
        r["source_url"] = ev if str(ev).startswith("http") else REPO_BLOB + fallback


def write(name, rows, fields):
    C.write_csv(os.path.join(D, name), rows, fields)


def main():
    req = [dict(zip(("id", "requirement", "status", "blocking_gate", "observed", "evidence_path", "category", "note"), r)) for r in REQ]
