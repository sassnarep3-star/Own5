#!/usr/bin/env python3
"""Deterministic compute for the 8ad92a0e desk (no clock, no network, no git).

Inputs  (committed, official-source): data/nfl-desk-8ad92a0e/
  standings_2026_reg_20261119.csv  - official standings read 2026-11-19
  results_2026_through_wk10.csv    - 150 finals (wk9+wk10 direct-read, rest reconciled 32/32)
  schedule_2026_wk11.csv           - 13 fixtures + 6 byes
Outputs (derived, regenerated byte-identically):
  lines_wk11.csv        13 games x 3 markets (side -> total -> moneyline), fair/market/diff separate
  price_snapshots.csv   one opening snapshot per originated market; market cells blank by policy
  correlations.csv      Pearson r from official numbers only, n published per row
  luck_panel.csv        chronological walk-forward Brier/MAE panel (skill vs baselines)
  model_spec.json       frozen model parameters + input hashes
All market-price cells stay empty: no licensed operator price source exists in scope (flag F8-01).
"""
import csv, hashlib, json, math, os
from collections import defaultdict

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DATA = os.path.join(BASE, 'data', 'nfl-desk-8ad92a0e')

# ---- frozen spec constants (documented, pre-registered) ----
K_SHRINK = 8.0          # shrinkage games constant
SIGMA_FALLBACK = 14.0   # used until >=2 prior margins exist (flagged assumption F8-06)
HFA_MIN_N = 10          # expanding HFA/sigma estimated from all prior games from n=1 onward
OPENED_AT = '2026-11-19T11:30:00Z'   # pinned snapshot open time (deterministic)
POLICY = 'P-8AD-01: market price columns remain blank until a licensed operator price source is onboarded'


def read_csv(name):
    with open(os.path.join(DATA, name), newline='') as f:
        return list(csv.DictReader(f))


def write_csv(name, rows, header):
    with open(os.path.join(DATA, name), 'w', newline='') as f:
        wr = csv.writer(f)
        wr.writerow(header)
        wr.writerows(rows)


def sha(s):
    return hashlib.sha256(s.encode()).hexdigest()[:16]


def norm_cdf(x):
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def mean(xs):
    return sum(xs) / len(xs)


def sd(xs):
    if len(xs) < 2:
        return None
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def fisher_ci(r, n):
    if n <= 3 or abs(r) >= 0.999999:
        return (None, None)
    z = 0.5 * math.log((1 + r) / (1 - r))
    se = 1 / math.sqrt(n - 3)
    lo, hi = z - 1.96 * se, z + 1.96 * se
    return (math.tanh(lo), math.tanh(hi))


def pearson(xs, ys):
    n = len(xs)
    mx, my = mean(xs), mean(ys)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    if sxx == 0 or syy == 0:
        return None
    return sxy / math.sqrt(sxx * syy)


def main():
    standings = read_csv('standings_2026_reg_20261119.csv')
    results = read_csv('results_2026_through_wk10.csv')
    schedule = read_csv('schedule_2026_wk11.csv')
    assert len(standings) == 32 and len(results) == 150

    st = {}
    for r in standings:
        gp = int(r['w']) + int(r['l']) + int(r['t'])
        st[r['club']] = dict(gp=gp, pf=int(r['pf']), pa=int(r['pa']))

    # league scoring mean from official totals (PF=PA identity)
    total_pf = sum(v['pf'] for v in st.values())
    league_games = len(results)
    L = total_pf / (2 * league_games)   # per-team per-game scoring mean

    # home margin & totals from the 150 official finals
    margins, totals = [], []
    for r in results:
        ap, hp = int(r['away_pts']), int(r['home_pts'])
        margins.append(hp - ap)
        totals.append(hp + ap)
    hfa = mean(margins)                       # n=150
    sigma = sd(margins)                       # n=150
    sigma_total = sd(totals)                  # n=150
    home_wins = sum(1 for m in margins if m > 0)
    decisive = sum(1 for m in margins if m != 0)

    # ---------- origination: side -> total -> moneyline ----------
    def rates(c):
        v = st[c]
        pf = (v['pf'] + L * K_SHRINK) / (v['gp'] + K_SHRINK)
        pa = (v['pa'] + L * K_SHRINK) / (v['gp'] + K_SHRINK)
        return pf, pa

    games = [r for r in schedule if r['game_id']]
    games.sort(key=lambda r: r['game_id'])
    lines, snaps = [], []
    for g in games:
        aw, hm = g['away'], g['home']
        pf_a, pa_a = rates(aw)
        pf_h, pa_h = rates(hm)
        exp_h = (pf_h + pa_a) / 2.0
        exp_a = (pf_a + pa_h) / 2.0
        margin = (exp_h - exp_a) + hfa          # expected home margin, pts (+ = home favored)
        total = exp_h + exp_a                   # HFA cancels in the total
        p_home = norm_cdf(margin / sigma)
        p_away = 1.0 - p_home
        inputs = (f"{aw}|{hm}|{st[aw]['gp']}|{st[hm]['gp']}|K={K_SHRINK}|HFA={hfa:.4f}|SIGMA={sigma:.4f}|L={L:.4f}")
        h = sha(inputs)
        src = g['source_url']
        # 1) SIDE
        lines.append([g['game_id'], '1-SIDE', aw, hm, 'SIDE',
                      f"{-margin:.1f}",            # operator-style home line (negative = home favored)
                      f"{margin:.1f}",             # expected margin home (+ = home favored)
                      f"{p_home:.4f}",
                      '', '', '', h, src])
        # 2) TOTAL
        lines.append([g['game_id'], '2-TOTAL', aw, hm, 'TOTAL',
                      f"{total:.1f}", f"{total:.1f}", '0.5000',
                      '', '', '', h, src])
        # 3) MONEYLINE
        lines.append([g['game_id'], '3-MONEYLINE', aw, hm, 'MONEYLINE',
                      f"HOME {p_home:.4f} / AWAY {p_away:.4f}",
                      f"HOME {p_home:.4f}", f"{p_home:.4f}",
                      '', '', '', h, src])
        for market, fair in (('SIDE', f"{-margin:.1f}"), ('TOTAL', f"{total:.1f}"),
                             ('MONEYLINE', f"HOME {p_home:.4f} / AWAY {p_away:.4f}")):
            snaps.append([f"SNAP-{g['game_id']}-{market}", g['game_id'], market, fair,
                          OPENED_AT, '', '', 'OPEN', POLICY, h, src])
    write_csv('lines_wk11.csv', lines,
              ['game_id', 'order', 'away', 'home', 'market', 'model_fair_line',
               'expected_home_margin_or_total', 'model_prob_home_or_over',
               'market_line', 'market_price', 'difference', 'inputs_sha256', 'source_url'])
    write_csv('price_snapshots.csv', snaps,
              ['snapshot_id', 'game_id', 'market', 'model_fair_line', 'opened_at',
               'market_open', 'market_close', 'status', 'policy', 'inputs_sha256', 'source_url'])

    # ---------- correlations: official numbers only, n published ----------
    src_st = 'https://www.nfl.com/standings/league/2026/REG'
    W = [int(r['w']) for r in standings]
    PA = [int(r['pa']) for r in standings]
    PF = [int(r['pf']) for r in standings]
    NET = [int(r['net']) for r in standings]
    PCT = [float(r['pct']) for r in standings]
    GP = [int(r['w']) + int(r['l']) + int(r['t']) for r in standings]
    PPG = [p / g for p, g in zip(PF, GP)]
    PAPG = [p / g for p, g in zip(PA, GP)]
    NETPG = [p / g for p, g in zip(NET, GP)]
    corr_defs = [
        ('PF', 'W', PF, W), ('PA', 'W', PA, W), ('NET', 'PCT', NET, PCT),
        ('PF', 'PA', PF, PA), ('PF/G', 'W', PPG, W), ('PA/G', 'W', PAPG, W),
        ('NET/G', 'PCT', NETPG, PCT), ('PF/G', 'PA/G', PPG, PAPG),
    ]
    corr_rows = []
    for i, (xk, yk, xs, ys) in enumerate(corr_defs, 1):
        r = pearson(xs, ys)
        lo, hi = fisher_ci(r, len(xs))
        corr_rows.append([f'C8-{i:02d}', xk, yk, f'{r:.4f}', len(xs),
                          '' if lo is None else f'{lo:.4f}', '' if hi is None else f'{hi:.4f}',
                          'Pearson r, Fisher-z 95% CI', src_st])
    # game-level correlation from official finals
    ap_pts = [int(r['away_pts']) for r in results]
    hp_pts = [int(r['home_pts']) for r in results]
    r_g = pearson(ap_pts, hp_pts)
    lo, hi = fisher_ci(r_g, len(ap_pts))
    corr_rows.append(['C8-09', 'away_pts', 'home_pts', f'{r_g:.4f}', len(ap_pts),
                      f'{lo:.4f}', f'{hi:.4f}', 'Pearson r, Fisher-z 95% CI',
                      'https://www.nfl.com/scores/2026/reg10'])
    write_csv('correlations.csv', corr_rows,
              ['corr_id', 'var_x', 'var_y', 'r', 'n', 'ci95_low', 'ci95_high', 'method', 'source_url'])

    # ---------- chronological walk-forward luck panel ----------
    # order: by date, feed order within a date (deterministic)
    ordered = sorted(results, key=lambda r: (r['date'], r['week'], r['game_id']))
    pf = defaultdict(float); pa = defaultdict(float); gp = defaultdict(int)
    past_margins = []
    pts_prior = 0.0; n_prior = 0
    rows_luck = []
    brier_model, brier_base_hr, brier_base_05, abs_err = [], [], [], []
    for r in ordered:
        a, h = r['away'], r['home']
        ap, hp = int(r['away_pts']), int(r['home_pts'])
        # expanding league mean from PRIOR games only (no lookahead)
        L_t = (pts_prior / (2.0 * n_prior)) if n_prior > 0 else 20.0
        # forecast from PRIOR games only (no lookahead)
        if gp[a] > 0 and gp[h] > 0:
            pf_a = (pf[a] + L_t * K_SHRINK) / (gp[a] + K_SHRINK)
            pa_a = (pa[a] + L_t * K_SHRINK) / (gp[a] + K_SHRINK)
            pf_h = (pf[h] + L_t * K_SHRINK) / (gp[h] + K_SHRINK)
            pa_h = (pa[h] + L_t * K_SHRINK) / (gp[h] + K_SHRINK)
            exp_h = (pf_h + pa_a) / 2.0
            exp_a = (pf_a + pa_h) / 2.0
        else:
            exp_h = exp_a = L_t  # no information yet: league mean each side
        if past_margins:
            hfa_t = mean(past_margins)
            s = sd(past_margins)
            sigma_t = s if s is not None else SIGMA_FALLBACK
        else:
            hfa_t, sigma_t = 0.0, SIGMA_FALLBACK
        m = (exp_h - exp_a) + hfa_t
        p = norm_cdf(m / sigma_t)
        if ap == hp:
            verdict = 'TIE-EXCLUDED'
        else:
            y = 1.0 if hp > ap else 0.0
            brier_model.append((p - y) ** 2)
            brier_base_05.append((0.5 - y) ** 2)
            base_hr = (sum(1 for x in past_margins if x > 0) / len(past_margins)) if past_margins else 0.5
            brier_base_hr.append((base_hr - y) ** 2)
            abs_err.append(abs(m - (hp - ap)))
            verdict = 'SCORED'
        rows_luck.append([r['game_id'], r['week'], r['date'], a, h, ap, hp,
                          f'{m:.2f}', f'{p:.4f}', verdict])
        # update AFTER forecasting
        pf[a] += ap; pa[a] += hp; gp[a] += 1
        pf[h] += hp; pa[h] += ap; gp[h] += 1
        pts_prior += ap + hp; n_prior += 1
        past_margins.append(hp - ap)

    def brier_skill(model, base):
        bm, bb = mean(model), mean(base)
        return bm, bb, (1 - bm / bb) if bb else None

    bm, b05, s05 = brier_skill(brier_model, brier_base_05)
    _, bhr, shr = brier_skill(brier_model, brier_base_hr)
    # week-cluster bootstrap CI for skill vs expanding home-rate baseline (deterministic seed)
    import random
    rng = random.Random(8_920_611)
    # per-game paired losses indexed by week for clustering
    week_idx = defaultdict(list)
    i = 0
    for row in rows_luck:
        if row[9] == 'SCORED':
            week_idx[row[1]].append(i)
            i += 1
    weeks = sorted(week_idx)
    skills = []
    for _ in range(1000):
        pick = [rng.choice(weeks) for _ in weeks]
        mi, bi = [], []
        for w in pick:
            mi.extend(brier_model[j] for j in week_idx[w])
            bi.extend(brier_base_hr[j] for j in week_idx[w])
        if mi and mean(bi) > 0:
            skills.append(1 - mean(mi) / mean(bi))
    skills.sort()
    lo_b = skills[int(0.025 * len(skills))]
    hi_b = skills[int(0.975 * len(skills))]

    luck_rows = [
        ['L8-01', 'Brier (home-win), walk-forward model', f'{bm:.4f}', len(brier_model),
         'chronological, prior-games-only inputs; ties excluded', 'results_2026_through_wk10.csv'],
        ['L8-02', 'Brier, baseline p=0.5', f'{b05:.4f}', len(brier_base_05), 'coin flip', 'results_2026_through_wk10.csv'],
        ['L8-03', 'Brier, baseline expanding home-win rate', f'{bhr:.4f}', len(brier_base_hr),
         'prior-games home-win rate (no lookahead)', 'results_2026_through_wk10.csv'],
        ['L8-04', 'Brier skill vs p=0.5 (1 - model/base)', f'{s05:.4f}', len(brier_model), 'positive = better than coin', 'results_2026_through_wk10.csv'],
        ['L8-05', 'Brier skill vs expanding home rate', f'{shr:.4f}', len(brier_model),
         f'week-cluster bootstrap 95% CI [{lo_b:.4f}, {hi_b:.4f}], 1000 resamples, seed 8920611', 'results_2026_through_wk10.csv'],
        ['L8-06', 'Side MAE (pts), walk-forward', f'{mean(abs_err):.4f}', len(abs_err),
         'mean |expected margin - actual margin|', 'results_2026_through_wk10.csv'],
        ['L8-07', 'Home win rate (official finals)', f'{home_wins / decisive:.4f}', decisive,
         f'{home_wins} home wins of {decisive} decisive; {len(margins) - decisive} ties excluded', 'results_2026_through_wk10.csv'],
        ['L8-08', 'Mean home margin (HFA estimate)', f'{hfa:.4f}', len(margins), 'pts, official finals', 'results_2026_through_wk10.csv'],
        ['L8-09', 'Margin sigma', f'{sigma:.4f}', len(margins), 'sd of home margins, official finals', 'results_2026_through_wk10.csv'],
        ['L8-10', 'Total sigma', f'{sigma_total:.4f}', len(totals), 'sd of game totals, official finals', 'results_2026_through_wk10.csv'],
    ]
    write_csv('luck_panel.csv', luck_rows,
              ['metric_id', 'metric', 'value', 'n', 'note', 'source_file'])

    spec = dict(
        model_id='m8-2026-11-19-walkforward-v1',
        shrinkage_k=K_SHRINK,
        sigma_fallback=SIGMA_FALLBACK,
        league_scoring_mean=round(L, 4),
        hfa_estimate_pts=round(hfa, 4), hfa_n=len(margins),
        sigma_margin=round(sigma, 4), sigma_total=round(sigma_total, 4),
        markets_per_game=3, games=len(games),
        market_policy=POLICY,
        inputs_sha256={
            'standings': sha(open(os.path.join(DATA, 'standings_2026_reg_20261119.csv')).read()),
            'results': sha(open(os.path.join(DATA, 'results_2026_through_wk10.csv')).read()),
            'schedule': sha(open(os.path.join(DATA, 'schedule_2026_wk11.csv')).read()),
        },
        walkforward_n_scored=len(brier_model),
        walkforward_brier=round(bm, 4),
        walkforward_skill_vs_home_rate=round(shr, 4),
        walkforward_skill_ci95=[round(lo_b, 4), round(hi_b, 4)],
    )
    with open(os.path.join(DATA, 'model_spec.json'), 'w') as f:
        json.dump(spec, f, indent=2, sort_keys=True)
        f.write('\n')

    print(f"OK lines={len(lines)} snapshots={len(snaps)} corr={len(corr_rows)} luck={len(luck_rows)}")
    print(f"HFA={hfa:.3f} (n={len(margins)}) sigma={sigma:.3f} L={L:.3f}")
    print(f"Brier={bm:.4f} skill_vs_home_rate={shr:.4f} CI=[{lo_b:.4f},{hi_b:.4f}] n={len(brier_model)}")
    print(f"MAE={mean(abs_err):.3f} home_win_rate={home_wins/decisive:.4f}")


if __name__ == '__main__':
    main()
